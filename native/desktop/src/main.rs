fn main() -> Result<()> {
    // Spanish when the system speaks it; English otherwise.
    if tr::spanish() {
        let _ = slint::select_bundled_translation("es");
    }
    let mut args = std::env::args().skip(1);
    if args.next().as_deref() == Some("--shot") {
        let dir = args.next().unwrap_or_else(|| "shots".into());
        return shot::all(std::path::Path::new(&dir));
    }
    // A check of what the old Desktop holds, counts only (TAWNY_DEV=1).
    if std::env::var_os("TAWNY_DEV").is_some_and(|v| v == "1")
        && std::env::args().nth(1).as_deref() == Some("--migrate-check")
    {
        return migrate_check();
    }
    if std::env::var_os("TAWNY_DEV").is_some_and(|v| v == "1")
        && std::env::args().nth(1).as_deref() == Some("--camera-check")
    {
        println!("{} camera(s)", camera::count());
        println!("{}", camera::check(0, 30)?);
        return Ok(());
    }
    if std::env::var_os("TAWNY_DEV").is_some_and(|v| v == "1")
        && std::env::args().nth(1).as_deref() == Some("--tip-check")
    {
        return tip::check();
    }
    // One Tawny at a time: a later copy hands its pairing link over and quits.
    let link = std::env::args()
        .nth(1)
        .filter(|a| a.starts_with("tawny://"));
    let _instance = match single::start(
        &store::default_dir()?,
        link.as_deref(),
        session::link_from_another_copy,
    )? {
        single::Start::First(i) => i,
        single::Start::Handed => return Ok(()),
    };
    let mut opened = store::Store::open_default()?;
    // An update from the old Desktop keeps its channels and pairings.
    match migrate::run(&mut opened) {
        Ok(r) if r.channels > 0 => {
            eprintln!(
                "tawny: brought over {} channel(s) from the old Desktop",
                r.channels
            );
        }
        Ok(_) => {}
        Err(e) => eprintln!("tawny: reading the old Desktop's storage: {e:#}"),
    }
    let store = Rc::new(RefCell::new(opened));
    let ui = AppWindow::new()?;
    let _scene = SceneDriver::attach(&ui);
    let host = session::Host::attach(&ui, store.clone())?;
    let sessions: Rc<dyn app::Sessions> = host.clone();
    app::attach(&ui, &store, &sessions);
    tip::attach(&ui, host.handle());
    // Opened with a pairing link (the system's tawny:// handler).
    if let Some(link) = std::env::args()
        .nth(1)
        .filter(|a| a.starts_with("tawny://"))
    {
        host.read_link(&ui, &link);
    }
    dev_hatch(&ui, &store, &sessions, &host);
    ui.run()?;
    Ok(())
}

/// What an import from the old Desktop would bring, into a scratch store:
/// counts and names of keys only, never their values.
fn migrate_check() -> Result<()> {
    for db in migrate::sources() {
        println!("source {}", db.display());
        match migrate::read_local_storage(&db) {
            Ok(items) => {
                let names: std::collections::BTreeSet<String> = items
                    .keys()
                    .map(|k| k.split('.').take(2).collect::<Vec<_>>().join("."))
                    .collect();
                println!(
                    "  {} items: {}",
                    items.len(),
                    names.into_iter().collect::<Vec<_>>().join(", ")
                );
                let scratch =
                    std::env::temp_dir().join(format!("tawny-check-{}", std::process::id()));
                let mut s = store::Store::open(&scratch.join("store.json"))?;
                let r = migrate::import(&items, &mut s);
                println!(
                    "  would bring {} channel(s), {} key entries",
                    r.channels, r.entries
                );
            }
            Err(e) => println!("  unreadable: {e:#}"),
        }
    }
    Ok(())
}

/// A developer's hatch for end-to-end runs (only with `TAWNY_DEV=1`):
/// `--monitor` starts a Monitor and prints its link; `--join <link>` joins one.
fn dev_hatch(
    ui: &AppWindow,
    store: &Rc<RefCell<store::Store>>,
    sessions: &Rc<dyn app::Sessions>,
    host: &session::Host,
) {
    if std::env::var_os("TAWNY_DEV").is_none_or(|v| v != "1") {
        return;
    }
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.first().map(String::as_str) {
        Some("--monitor") => {
            let ch = {
                let mut s = store.borrow_mut();
                match s.data.channels.first().cloned() {
                    Some(c) => c,
                    None => s.add_channel("E2E"),
                }
            };
            sessions.start(ui, &mut store.borrow_mut(), &ch, store::Role::Station);
            println!("LINK {}", ui.get_pair_link());
        }
        Some("--join") => {
            if let Some(link) = args.get(1) {
                host.read_link(ui, link);
                host.join_now(ui);
                // TAWNY_MYCAM=1: switch My camera on 12 s in.
                if std::env::var_os("TAWNY_MYCAM").is_some_and(|v| v == "1") {
                    let w = ui.as_weak();
                    slint::Timer::single_shot(std::time::Duration::from_secs(12), move || {
                        if let Some(ui) = w.upgrade() {
                            ui.global::<Live>().invoke_camera();
                        }
                    });
                }
                // TAWNY_RECORD=1: press Record 10 s in (it stops itself at 20 s).
                if std::env::var_os("TAWNY_RECORD").is_some_and(|v| v == "1") {
                    let w = ui.as_weak();
                    slint::Timer::single_shot(std::time::Duration::from_secs(10), move || {
                        if let Some(ui) = w.upgrade() {
                            ui.global::<Live>().invoke_record();
                        }
                    });
                }
                // TAWNY_TALK=1: hold Talk from 8 s in, as a thumb would.
                if std::env::var_os("TAWNY_TALK").is_some_and(|v| v == "1") {
                    let w = ui.as_weak();
                    slint::Timer::single_shot(std::time::Duration::from_secs(8), move || {
                        if let Some(ui) = w.upgrade() {
                            ui.global::<Live>().invoke_talk(true);
                        }
                    });
                }
            }
        }
        _ => {}
    }
}

/// Keeps the pictures drawn: the welcome trio and the Support card's owlet,
/// a frame whenever one moves, at the size and scale it is shown at, in the
/// theme's colours. Only the picture on the screen that is up is drawn.
pub struct SceneDriver {
    _timer: Timer,
}

/// One picture and what it was last drawn for (dark, width, height).
struct Stage {
    scene: Scene,
    drawn: Option<(bool, u32, u32)>,
}

/// Where a picture lives in the window.
#[derive(Clone, Copy)]
enum Spot {
    Welcome,
    Owlet,
    Hub,
    /// Tawny on the tip's QR plate.
    TipOwl,
    /// The trio on the thank-you.
    Party,
}

impl Spot {
    fn size(self, ui: &AppWindow) -> (f32, f32) {
        match self {
            Self::Welcome => (ui.get_scene_width(), ui.get_scene_height()),
            Self::Owlet => (ui.get_owlet_width(), ui.get_owlet_height()),
            Self::Hub => (ui.get_hub_scene_width(), ui.get_hub_scene_height()),
            Self::TipOwl => {
                let t = ui.global::<Tip>();
                (t.get_owl_width(), t.get_owl_height())
            }
            Self::Party => {
                let t = ui.global::<Tip>();
                (t.get_party_width(), t.get_party_height())
            }
        }
    }
    fn set(self, ui: &AppWindow, img: Image) {
        match self {
            Self::Welcome => ui.set_scene(img),
            Self::Owlet => ui.set_owlet(img),
            Self::Hub => ui.set_hub_scene(img),
            Self::TipOwl => ui.global::<Tip>().set_owl(img),
            Self::Party => ui.global::<Tip>().set_party(img),
        }
    }
}

impl SceneDriver {
    #[must_use]
    pub fn attach(ui: &AppWindow) -> Self {
        let still = ui.global::<Theme>().get_still();
        let trio = Rc::new(RefCell::new(Stage {
            scene: Scene::new(still),
            drawn: None,
        }));
        let owlet = Rc::new(RefCell::new(Stage {
            scene: Scene::owlet(still),
            drawn: None,
        }));
        let hub = Rc::new(RefCell::new(Stage {
            scene: Scene::new(still),
            drawn: None,
        }));
        let tip_owl = Rc::new(RefCell::new(Stage {
            scene: Scene::owlet(still),
            drawn: None,
        }));
        let party = Rc::new(RefCell::new(Stage {
            scene: Scene::new(still),
            drawn: None,
        }));
        let born = Instant::now();
        let s = tip_owl.clone();
        ui.global::<Tip>().on_owl_tapped(move |x, y, w, h| {
            s.borrow_mut()
                .scene
                .tap(x, y, w, h, born.elapsed().as_secs_f32());
        });
        let s = party.clone();
        ui.global::<Tip>().on_party_tapped(move |x, y, w, h| {
            s.borrow_mut()
                .scene
                .tap(x, y, w, h, born.elapsed().as_secs_f32());
        });
        let s = hub.clone();
        ui.on_hub_scene_tapped(move |x, y, w, h| {
            s.borrow_mut()
                .scene
                .tap(x, y, w, h, born.elapsed().as_secs_f32());
        });
        let s = trio.clone();
        ui.on_scene_tapped(move |x, y, w, h| {
            s.borrow_mut()
                .scene
                .tap(x, y, w, h, born.elapsed().as_secs_f32());
        });
        let s = owlet.clone();
        ui.on_owlet_tapped(move |x, y, w, h| {
            s.borrow_mut()
                .scene
                .tap(x, y, w, h, born.elapsed().as_secs_f32());
        });
        let timer = Timer::default();
        let weak = ui.as_weak();
        timer.start(TimerMode::Repeated, Duration::from_millis(33), move || {
            let Some(ui) = weak.upgrade() else { return };
            let now = born.elapsed().as_secs_f32();
            let hops = crate::tip::take_flutter();
            if hops > 0 {
                tip_owl.borrow_mut().scene.flutter(hops, now);
            }
            if crate::tip::take_cheer() {
                party.borrow_mut().scene.cheer(now);
            }
            // A sheet's picture first: it is what is in front.
            let (stage, spot) = if ui.get_sheet() == "tip" {
                match ui.global::<Tip>().get_page().as_str() {
                    "pick" => (&tip_owl, Spot::TipOwl),
                    "thanks" => (&party, Spot::Party),
                    _ => (&hub, Spot::Hub),
                }
            } else {
                match ui.get_screen().as_str() {
                    "welcome" => (&trio, Spot::Welcome),
                    "channels" => (&owlet, Spot::Owlet),
                    _ => return,
                }
            };
            let mut st = stage.borrow_mut();
            st.scene.still = ui.global::<Theme>().get_still();
            paint(&ui, &mut st, spot, now);
        });
        Self { _timer: timer }
    }
}

/// Draws a stage into its spot, unless it is still and already drawn as it
/// would be now.
fn paint(ui: &AppWindow, st: &mut Stage, spot: Spot, now: f32) {
    let dark = ui.global::<Theme>().get_dark();
    let (w, h) = spot.size(ui);
    let Some((img, pw, ph)) = picture(ui, &st.scene, w, h, now, dark) else {
        return;
    };
    let key = Some((dark, pw, ph));
    if st.drawn == key && !st.scene.animating(now) {
        return;
    }
    st.drawn = key;
    spot.set(ui, img);
}

/// The scene drawn at `w`×`h` logical pixels (the window's scale applied),
/// with its size in physical pixels.
#[expect(
    clippy::cast_possible_truncation,
    clippy::cast_sign_loss,
    reason = "clamped to 1..=8192 first"
)]
fn picture(
    ui: &AppWindow,
    sc: &Scene,
    w: f32,
    h: f32,
    now: f32,
    dark: bool,
) -> Option<(Image, u32, u32)> {
    let scale = ui.window().scale_factor();
    let px = |v: f32| (v * scale).round().clamp(1.0, 8192.0) as u32;
    let (w, h) = (px(w), px(h));
    let palette = if dark {
        Palette::dark()
    } else {
        Palette::light()
    };
    let pm = sc.render(w, h, now, palette)?;
    let buf = SharedPixelBuffer::<Rgba8Pixel>::clone_from_slice(pm.data(), w, h);
    Some((Image::from_rgba8_premultiplied(buf), w, h))
}

/// Draws a still frame of both pictures at their current sizes (the shots).
pub fn draw_stills(ui: &AppWindow) {
    let dark = ui.global::<Theme>().get_dark();
    for (sc, spot) in [
        (Scene::new(true), Spot::Welcome),
        (Scene::owlet(true), Spot::Owlet),
        (Scene::new(true), Spot::Hub),
        (Scene::owlet(true), Spot::TipOwl),
        (Scene::new(true), Spot::Party),
    ] {
        let (w, h) = spot.size(ui);
        if let Some((img, _, _)) = picture(ui, &sc, w, h, 0.0, dark) {
            spot.set(ui, img);
        }
    }
}
